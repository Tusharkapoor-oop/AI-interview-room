def _compute_ks_2samp(data1: List[float], data2: List[float]) -> Tuple[float, float]:
    """
    Pure numpy implementation of Two-Sample Kolmogorov-Smirnov test.
    Returns (ks_statistic, p_value).
    """
    n1 = len(data1)
    n2 = len(data2)
    if n1 == 0 or n2 == 0:
        return 0.0, 1.0

    d1_sorted = np.sort(data1)
    d2_sorted = np.sort(data2)
    all_vals = np.concatenate([d1_sorted, d2_sorted])
    
    # Compute ECDFs at all concatenated points
    cdf1 = np.searchsorted(d1_sorted, all_vals, side='right') / n1
    cdf2 = np.searchsorted(d2_sorted, all_vals, side='right') / n2
    
    ks_stat = float(np.max(np.abs(cdf1 - cdf2)))
    
    # Compute asymptotic p-value using Kolmogorov survival function
    ne = (n1 * n2) / (n1 + n2)
    lam = (math.sqrt(ne) + 0.12 + 0.11 / math.sqrt(ne)) * ks_stat
    
    if lam < 0.2:
        p_val = 1.0
    else:
        # 2 * sum_{j=1}^{10} (-1)^(j-1) * exp(-2 * j^2 * lam^2)
        p_val = 0.0
        for j in range(1, 15):
            term = 2.0 * ((-1.0)**(j - 1)) * math.exp(-2.0 * (j**2) * (lam**2))
            p_val += term
            if abs(term) < 1e-8:
                break
        p_val = max(0.0, min(1.0, p_val))
        
    return ks_stat, p_val


# ─── DATA CONTRACTS ─────────────────────────────────────────────────────────────

@dataclass
class ForensicObservation:
    """Frame-by-frame telemetry packet fed into the forensic engine."""
    timestamp: float
    gaze_angular_deviation: float       # Degrees from optical axis
    gaze_screen_coords: Tuple[float, float] # (x, y) normalized 0-1
    pupil_diameter_mm: float            # Estimated pupil diameter
    screen_brightness_level: float      # Current screen stimulus (0.0 to 1.0)
    facial_rgb_mean: Tuple[float, float, float] # Mean RGB of forehead/cheek ROI
    candidate_speaking: bool            # Contextual audio flag
    keyboard_typing_active: bool        # True if burst typing is occurring


@dataclass
class ForensicAlert:
    """Standardized alert generated by forensic modules."""
    module_name: str
    alert_type: str                     # KS_ANOMALY | WHITESPACE_FIXATION | PLR_FAIL | RPPG_FAIL
    severity: str                       # LOW | MEDIUM | HIGH | CRITICAL
    confidence: float                   # 0.0 to 1.0
    description: str
    timestamp: float
    metrics: Dict[str, float] = field(default_factory=dict)


# ─── MODULE 8: KS-TEST STATISTICAL GAZE BASELINE ENGINE ────────────────────────

class KSTestBaselineEngine:
    """
    Module 8: KS-Test Statistical Gaze Baseline Engine.
    
    Solves universal threshold problem (theta > 25 deg).
    Collects personal calibration point cloud (first 90s).
    Performs Two-Sample Kolmogorov-Smirnov test on rolling 10s active window.
    Rejects H0 (flags anomaly) when p < 0.05.
    Contextually suppresses flags when candidate is actively speaking.
    """

    def __init__(self, calibration_duration_sec: float = 90.0, window_duration_sec: float = 10.0):
        self.calib_duration = calibration_duration_sec
        self.window_duration = window_duration_sec
        
        self.is_calibrated: bool = False
        self.start_time: Optional[float] = None
        
        # Baseline point cloud (stored during calibration)
        self.baseline_deviations: List[float] = []
        
        # Rolling active buffer: list of (timestamp, deviation)
        self.active_buffer: List[Tuple[float, float]] = []

    def process(self, obs: ForensicObservation) -> Optional[ForensicAlert]:
        if self.start_time is None:
            self.start_time = obs.timestamp

        elapsed = obs.timestamp - self.start_time

        # 1. Calibration Phase
        if not self.is_calibrated:
            self.baseline_deviations.append(obs.gaze_angular_deviation)
            if elapsed >= self.calib_duration and len(self.baseline_deviations) >= 50:
                self.is_calibrated = True
                log.info(f"[Module 8] KS-Test Baseline Calibrated over {len(self.baseline_deviations)} frames.")
            return None

        # 2. Continuous Active Phase: maintain rolling 10-second window
        self.active_buffer.append((obs.timestamp, obs.gaze_angular_deviation))
        self.active_buffer = [item for item in self.active_buffer if obs.timestamp - item[0] <= self.window_duration]

        if len(self.active_buffer) < 30:
            return None

        # 3. Contextual Suppression Check [ZERO-COMPROMISE rule enforcement]
        if obs.candidate_speaking:
            # Natural cognitive drift during speech is expected; suppress gaze flags
            return None

        active_deviations = [item[1] for item in self.active_buffer]

        # 4. Perform Two-Sample Kolmogorov-Smirnov Test
        # H0: active window and personal baseline come from identical continuous distributions
        ks_stat, p_value = _compute_ks_2samp(self.baseline_deviations, active_deviations)

        # 5. Evaluate Rejection Criterion (p < 0.05)
        if p_value < 0.05:
            # Calculate shift direction
            active_mean = float(np.mean(active_deviations))
            base_mean = float(np.mean(self.baseline_deviations))
            
            if active_mean > base_mean * 1.3:
                severity = "HIGH" if p_value < 0.01 else "MEDIUM"
                return ForensicAlert(
                    module_name="M8_KS_Test_Baseline",
                    alert_type="KS_ANOMALY",
                    severity=severity,
                    confidence=float(1.0 - p_value),
                    description=f"Significant gaze distribution shift (p={p_value:.4f}, KS={ks_stat:.3f}). Active mean={active_mean:.1f}° vs Baseline={base_mean:.1f}°.",
                    timestamp=obs.timestamp,
                    metrics={"p_value": float(p_value), "ks_stat": float(ks_stat), "active_mean_deg": active_mean}
                )

        return None


# ─── MODULE 7: WHITESPACE FIXATION DETECTOR ────────────────────────────────────

class WhitespaceFixationDetector:
    """
    Module 7: Whitespace Fixation Detector.
    
    Solves Cluely / Interview Coder OS-level transparent overlay exploit.
    Maps gaze screen coordinates against known UI content vs whitespace zones.
    Flags when whitespace_ratio > 0.4 (40% of fixations in blank regions).
    Correlates with keyboard typing activity for confidence boosting.
    """

    def __init__(self, window_size_frames: int = 150):
        self.window_size = window_size_frames
        self.history: List[Tuple[float, float, bool]] = []  # (x, y, is_typing)
        
        # Default layout representation: content is center box [0.2 to 0.8 across X and Y]
        # Whitespace zones are side margins (where transparent reading windows are placed)
        self.content_bounds = {"x_min": 0.20, "x_max": 0.80, "y_min": 0.15, "y_max": 0.85}

    def _is_in_whitespace(self, x: float, y: float) -> bool:
        if x < self.content_bounds["x_min"] or x > self.content_bounds["x_max"]:
            return True
        if y < self.content_bounds["y_min"] or y > self.content_bounds["y_max"]:
            return True
        return False

    def process(self, obs: ForensicObservation) -> Optional[ForensicAlert]:
        x, y = obs.gaze_screen_coords
        self.history.append((x, y, obs.keyboard_typing_active))
        if len(self.history) > self.window_size:
            self.history.pop(0)

        if len(self.history) < 60:
            return None

        # Calculate kernel density proportion in whitespace
        whitespace_count = sum(1 for item in self.history if self._is_in_whitespace(item[0], item[1]))
        whitespace_ratio = float(whitespace_count) / float(len(self.history))

        # Check typing correlation
        typing_in_whitespace = sum(1 for item in self.history if self._is_in_whitespace(item[0], item[1]) and item[2])
        typing_ratio = float(typing_in_whitespace) / max(whitespace_count, 1)

        # Anomaly threshold: whitespace_ratio > 0.40
        if whitespace_ratio > 0.40:
            confidence = min(0.65 + (whitespace_ratio - 0.40) * 1.5, 0.99)
            severity = "MEDIUM"
            desc = f"Gaze concentrating on UI whitespace ({whitespace_ratio*100:.1f}% of fixations)."
            
            if typing_ratio > 0.50:
                confidence = 0.98
                severity = "HIGH"
                desc = f"Candidate actively typing while looking exclusively at blank UI margin ({whitespace_ratio*100:.1f}% ratio). Suspicion of transparent OS overlay."

            return ForensicAlert(
                module_name="M7_Whitespace_Fixation",
                alert_type="WHITESPACE_FIXATION",
                severity=severity,
                confidence=float(confidence),
                description=desc,
                timestamp=obs.timestamp,
                metrics={"whitespace_ratio": whitespace_ratio, "typing_correlation": typing_ratio}
            )

        return None


# ─── MODULE 6: PLR + RPPG COMBINED LIVENESS ENGINE ─────────────────────────────

class PLRrPPGLivenessEngine:
    """
    Module 6: PLR + rPPG Combined Liveness Engine.
    
    Active 10-second challenge:
    1. PLR (Pupillary Light Reflex): Synchronized brightness cycling (0.5-2.0 Hz).
       Live pupil constricts when screen transitions dark -> bright within <300ms.
    2. rPPG (remote Photoplethysmography): RGB skin variations -> luminance FFT -> 60-100 BPM.
    
    BOTH signals required for live verification.
    """

    def __init__(self, challenge_duration_sec: float = 10.0):
        self.duration = challenge_duration_sec
        self.buffer: List[Tuple[float, float, float, Tuple[float, float, float]]] = []
        # (timestamp, brightness, pupil_mm, rgb)

    def process(self, obs: ForensicObservation) -> Optional[ForensicAlert]:
        self.buffer.append((obs.timestamp, obs.screen_brightness_level, obs.pupil_diameter_mm, obs.facial_rgb_mean))
        
        # Keep rolling 10-second window
        self.buffer = [item for item in self.buffer if obs.timestamp - item[0] <= self.duration]

        # Evaluate only when full 10-second window accumulated (~300 frames at 30 FPS)
        if len(self.buffer) < 250:
            return None

        # ── 1. Evaluate PLR (Pupillary Light Reflex) ──
        # Find dark -> bright transitions
        plr_passed = False
        plr_latencies = []
        
        for i in range(10, len(self.buffer) - 15):
            t_prev, b_prev, p_prev, _ = self.buffer[i-1]
            t_curr, b_curr, p_curr, _ = self.buffer[i]
            
            # Step transition: brightness jumps by >= 0.5
            if b_curr - b_prev >= 0.5:
                # Look ahead up to 400ms for pupil constriction
                min_pupil = p_curr
                min_time = t_curr
                for j in range(i+1, min(i+15, len(self.buffer))):
                    tj, bj, pj, _ = self.buffer[j]
                    if pj < min_pupil:
                        min_pupil = pj
                        min_time = tj
                        
                constriction_delta = p_curr - min_pupil
                latency_ms = (min_time - t_curr) * 1000.0
                
                # Live human: constriction > 0.2mm within 300ms
                if constriction_delta >= 0.15 and 20.0 <= latency_ms <= 320.0:
                    plr_passed = True
                    plr_latencies.append(latency_ms)

        # ── 2. Evaluate rPPG (Heartbeat Extraction via FFT) ──
        # Extract luminance: L = 0.3R + 0.59G + 0.11B
        luminance = np.array([0.3*item[3][0] + 0.59*item[3][1] + 0.11*item[3][2] for item in self.buffer])
        timestamps = np.array([item[0] for item in self.buffer])
        
        # Detrend and window
        luminance_clean = luminance - np.mean(luminance)
        window = np.hanning(len(luminance_clean))
        fft_out = np.abs(np.fft.rfft(luminance_clean * window))
        freqs = np.fft.rfftfreq(len(luminance_clean), d=np.mean(np.diff(timestamps)))
        
        # Human heart rate band: 1.0 Hz (60 BPM) to 1.66 Hz (100 BPM)
        valid_idx = np.where((freqs >= 0.9) & (freqs <= 2.2))[0]
        rppg_passed = False
        bpm_est = 0.0
        
        if len(valid_idx) > 0:
            peak_idx = valid_idx[np.argmax(fft_out[valid_idx])]
            peak_freq = freqs[peak_idx]
            bpm_est = float(peak_freq * 60.0)
            
            # Signal-to-noise ratio check
            snr = fft_out[peak_idx] / (np.mean(fft_out) + 1e-9)
            if 55.0 <= bpm_est <= 130.0 and snr >= 3.0:
                rppg_passed = True

        # ── 3. Combined Decision Matrix ──
        if not plr_passed and not rppg_passed:
            return ForensicAlert(
                module_name="M6_PLR_rPPG_Dual",
                alert_type="SPOOFING_ATTEMPT",
                severity="CRITICAL",
                confidence=0.99,
                description="Complete absence of biological liveness. Neither Pupillary Light Reflex (PLR) nor pulsatile blood volume (rPPG) detected. High probability of static video spoof or generative deepfake.",
                timestamp=obs.timestamp,
                metrics={"plr_passed": 0.0, "rppg_passed": 0.0, "estimated_bpm": bpm_est}
            )
        elif not plr_passed:
            return ForensicAlert(
                module_name="M6_PLR_rPPG_Dual",
                alert_type="PLR_FAIL",
                severity="HIGH",
                confidence=0.88,
                description="Pupil failed to constrict within <300ms threshold during illumination spike. Potential eye replacement deepfake or corneal replay.",
                timestamp=obs.timestamp,
                metrics={"plr_passed": 0.0, "rppg_passed": 1.0, "estimated_bpm": bpm_est}
            )
        elif not rppg_passed:
            return ForensicAlert(
                module_name="M6_PLR_rPPG_Dual",
                alert_type="RPPG_FAIL",
                severity="HIGH",
                confidence=0.85,
                description="Failed to extract biological photoplethysmogram (rPPG) pulse waveform from facial region.",
                timestamp=obs.timestamp,
                metrics={"plr_passed": 1.0, "rppg_passed": 0.0, "estimated_bpm": bpm_est}
            )

        return None
